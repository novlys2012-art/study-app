"""Split the single-file quiz site (kviz-final/index.html) into the Vite layout.

Usage: python3 tools/split-legacy.py path/to/kviz-final/index.html

Writes index.html, src/styles/legacy.css, src/data/{fu,mat,es}.js and src/legacy/app.js.
Line ranges match kviz-final at commit 0370ef3; the script stops if they no longer fit.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
src = Path(sys.argv[1]).read_text(encoding="utf-8").split("\n")
L = lambda a, b: src[a - 1:b]  # 1-based, inclusive

def expect(n, prefix):
    if not src[n - 1].startswith(prefix):
        sys.exit(f"line {n} should start with {prefix!r}, found {src[n - 1][:60]!r}")

for n, p in [(15, "<style>"), (478, "</style>"), (646, "<script>"), (2739, "</script>"),
             (650, "const FU_Q"), (663, "const FU_T"), (664, "const MAT_G"), (668, "const MAT_CT"),
             (1049, "const ES_TOPICS"), (1723, "];"), (1725, "const ES_GLOSS"), (1774, "const ES_TR"),
             (1867, "const ES_CARDS"), (1878, "};")]:
    expect(n, p)

DATA = {
    "fu": [(650, 653), (663, 663)],
    "mat": [(664, 668)],
    "es": [(1043, 1723), (1725, 1770), (1772, 1810), (1866, 1878)],
}
HEADER = "// Generated by tools/split-legacy.py from kviz-final/index.html. Edit here from now on.\n"

def exportify(lines):
    return [("export " + l) if l.startswith("const ") else l for l in lines]

taken = set()
names = {}
for mod, ranges in DATA.items():
    out = []
    for a, b in ranges:
        out += exportify(L(a, b))
        taken.update(range(a, b + 1))
    names[mod] = re.findall(r"^export const (\w+)", "\n".join(out), re.M)
    (ROOT / "src/data").mkdir(parents=True, exist_ok=True)
    (ROOT / f"src/data/{mod}.js").write_text(HEADER + "\n".join(out).rstrip(";\n") + ";\n", encoding="utf-8")

# The rest of the script becomes one module that imports the data.
imports = [f'import {{ {", ".join(v)} }} from "../data/{k}.js";' for k, v in names.items()]
logic = [l for n, l in enumerate(src[646:2738], start=647) if n not in taken]
(ROOT / "src/legacy").mkdir(parents=True, exist_ok=True)
(ROOT / "src/legacy/app.js").write_text(
    "// Study modes carried over from kviz-final. Split further as features are rebuilt.\n"
    + "\n".join(imports) + "\n\n" + "\n".join(logic) + "\n", encoding="utf-8")

(ROOT / "src/styles").mkdir(parents=True, exist_ok=True)
(ROOT / "src/styles/legacy.css").write_text("\n".join(L(16, 477)) + "\n", encoding="utf-8")

# Page shell: head without inline CSS or analytics, body markup, one module entry.
head = [l for l in L(1, 14) if "goatcounter" not in l]
html = head + ["</head>"] + L(480, 644) + ['<script type="module" src="/src/main.js"></script>', "</body>", "</html>", ""]
(ROOT / "index.html").write_text("\n".join(html), encoding="utf-8")
print({k: len(v) for k, v in names.items()}, "logic lines:", len(logic))
